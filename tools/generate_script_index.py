#!/usr/bin/env python3
"""Generate a metadata-only navigation index; no source bodies or background jobs."""
import argparse
import hashlib
import json
import os
from pathlib import Path


EXCLUDED={'.git','.venv','.pytest_cache','__pycache__','node_modules','build',
          'recordings','oldrecordings','reports','assets'}
KINDS={'.py':'Python','.sh':'Shell','.cmd':'Windows batch','.ps1':'PowerShell','.cpp':'C++','.h':'C++ header','.c':'C',
       '.cjs':'JavaScript test','.html':'Browser app','.lua':'Luau','.luau':'Luau'}


def inventory(root):
    entries=[]
    mappings=[]
    for folder,dirs,files in os.walk(root,followlinks=False):
        dirs[:]=sorted(d for d in dirs if d not in EXCLUDED
                       and not (Path(folder)/d).is_symlink())
        for name in sorted(files):
            path=Path(folder)/name
            if path.is_symlink():
                continue
            rel=path.relative_to(root).as_posix()
            mapping=name.endswith('.project.json') or name.endswith('sourcemap.json')
            if mapping:
                mappings.append(rel)
            if path.suffix not in KINDS and not mapping:
                continue
            entries.append((rel,KINDS.get(path.suffix,'Rojo metadata')))
    return sorted(entries),sorted(mappings)


def render(root):
    entries,mappings=inventory(root)
    fingerprint=hashlib.sha256(json.dumps(entries).encode()).hexdigest()
    lines=['# Script index','',
        'Generated by `python3 tools/generate_script_index.py`; verify freshness with `--check`.',
        'Search the relevant row, then read that file and its necessary dependencies.',
        'Fingerprint uses paths and file types and is stable across fresh checkouts.',
        f'Inventory fingerprint: `{fingerprint}`.','',
        'This checkout is an external Python/C++ solver, not a Roblox place source tree.',
        'Roblox Explorer paths and Script/LocalScript/ModuleScript classes are not applicable',
        'to host code. Studio-only objects are unverified and are not enumerated here.']
    if mappings:
        lines.extend(['','Rojo metadata detected: '+', '.join(f'`{p}`' for p in mappings)+'.',
            '**Mapping is unverified:** inspect these files and obtain a current sourcemap',
            'before assigning Roblox Explorer paths or execution realms.'])
    else:
        lines.extend(['','No Rojo project configuration or sourcemap exists in this inventory.'])
    lines.extend(['','| Name | Type / Roblox class | Filesystem path | Explorer path | Realm | Evidence |',
        '| --- | --- | --- | --- | --- | --- |'])
    for rel,kind in entries:
        path=Path(rel)
        realm=('Host test' if rel.startswith('tests/') else
               'Browser' if rel.startswith('simulator/') else 'Host')
        roblox='N/A'
        if kind=='Luau':
            roblox=('Script' if '.server.' in path.name else
                    'LocalScript' if '.client.' in path.name else 'ModuleScript')+' (unverified filename inference)'
            realm='Unverified'
        lines.append(f'| {path.name} | {kind}; {roblox} | `{rel}` | '
                     f'{"Unverified" if kind=="Luau" else "N/A"} | {realm} | Filesystem metadata |')
    lines.extend(['','Regenerate after adding, deleting, renaming or editing source files.',
        'A stale index is a navigation hint, never the source of truth.',''])
    return '\n'.join(lines)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    args=parser.parse_args(argv)
    root=args.root.resolve()
    target=root/'docs/SCRIPT_INDEX.md'
    expected=render(root)
    if args.check:
        if not target.exists() or target.read_text()!=expected:
            print('Script index is stale; run python3 tools/generate_script_index.py')
            return 1
        print('Script index is current')
        return 0
    target.parent.mkdir(parents=True,exist_ok=True)
    if not target.exists() or target.read_text()!=expected:
        target.write_text(expected)
    print(f'Updated {target}')
    return 0


if __name__=='__main__':
    raise SystemExit(main())
